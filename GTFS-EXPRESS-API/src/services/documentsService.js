const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const parseTime = (t) => readTime(t, { strict: false });
const hhmm = (s) => formatTime(s, { seconds: false, round: false, clamp: false });
const todayYmd = () => {
  const d = new Date();
  return `${d.getUTCFullYear()}${String(d.getUTCMonth() + 1).padStart(2, "0")}${String(d.getUTCDate()).padStart(2, "0")}`;
};
const addDays = (ymd, n) => {
  const d = new Date(Date.UTC(+ymd.slice(0, 4), +ymd.slice(4, 6) - 1, +ymd.slice(6, 8) + n));
  return `${d.getUTCFullYear()}${String(d.getUTCMonth() + 1).padStart(2, "0")}${String(d.getUTCDate()).padStart(2, "0")}`;
};
const prettyDate = (ymd, l) => {
  const d = new Date(Date.UTC(+ymd.slice(0, 4), +ymd.slice(4, 6) - 1, +ymd.slice(6, 8)));
  return `${l.days[d.getUTCDay()]} ${ymd.slice(6, 8)}/${ymd.slice(4, 6)}/${ymd.slice(0, 4)}`;
};
const textColorFor = (hex) => {
  const h = /^[0-9A-Fa-f]{6}$/.test(hex || "") ? hex : "1E88E5";
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255 > 0.6 ? "111111" : "FFFFFF";
};

const resolveServiceDate = (db, date) => {
  const calendar = db.prepare("SELECT * FROM calendar").all();
  const calendarDates = db.prepare("SELECT service_id, date, exception_type FROM calendar_dates").all();
  for (let i = 0; i <= LOOKAHEAD_DAYS; i++) {
    const d = addDays(date, i);
    const ids = getServiceIdsForDate(d, calendar, calendarDates);
    if (ids.length) return { date: d, requested: date, shifted: i > 0, services: new Set(ids) };
  }
  return { date, requested: date, shifted: false, services: new Set() };
};

const dayTrips = (db, services, { routeId = null, stopId = null } = {}) => {
  const where = routeId ? "WHERE t.route_id = ?" : "";
  const trips = new Map();
  for (const t of db.prepare(`SELECT t.trip_id, t.route_id, t.service_id, t.direction_id, t.trip_headsign FROM trips t ${where}`).iterate(...(routeId ? [routeId] : []))) {
    if (!services.has(t.service_id)) continue;
    trips.set(t.trip_id, { trip_id: t.trip_id, route_id: t.route_id, direction_id: t.direction_id === "1" ? "1" : "0", headsign: t.trip_headsign || "", stops: [] });
    if (trips.size > MAX_TRIPS) break;
  }
  if (!trips.size) return [];
  const ids = [...trips.keys()];
  const chunk = 500;
  for (let i = 0; i < ids.length; i += chunk) {
    const part = ids.slice(i, i + chunk);
    const rows = db.prepare(`SELECT trip_id, stop_id, arrival_time, departure_time, stop_sequence FROM stop_times WHERE trip_id IN (${part.map(() => "?").join(",")}) ORDER BY trip_id, CAST(stop_sequence AS INTEGER)`).all(...part);
    for (const r of rows) trips.get(r.trip_id).stops.push({ stop_id: r.stop_id, dep: parseTime(r.departure_time || r.arrival_time) });
  }
  const freqs = new Map();
  try {
    for (const f of db.prepare("SELECT trip_id, start_time, end_time, headway_secs FROM frequencies").iterate()) {
      if (!trips.has(f.trip_id)) continue;
      const s = parseTime(f.start_time);
      const e = parseTime(f.end_time);
      const h = parseInt(f.headway_secs, 10);
      if (s == null || e == null || !(h > 0)) continue;
      if (!freqs.has(f.trip_id)) freqs.set(f.trip_id, []);
      freqs.get(f.trip_id).push({ start: s, end: e, headway: h });
    }
  } catch {
    /* no frequencies table */
  }
  const out = [];
  for (const t of trips.values()) {
    if (t.stops.length < 2 || t.stops[0].dep == null) continue;
    if (stopId && !t.stops.some((s) => s.stop_id === stopId)) continue;
    const fr = freqs.get(t.trip_id);
    if (!fr) {
      out.push(t);
      continue;
    }
    const first = t.stops[0].dep;
    for (const f of fr) {
      let k = 0;
      for (let x = f.start; x < f.end && k < MAX_FREQ_DEPARTURES; x += f.headway, k++) out.push({ ...t, trip_id: `${t.trip_id}@${hhmm(x)}`, stops: t.stops.map((s) => ({ stop_id: s.stop_id, dep: s.dep == null ? null : s.dep + (x - first) })) });
    }
  }
  return out;
};

const hourGrid = (deps) => {
  const byHour = new Map();
  for (const s of deps) {
    const h = Math.floor(s / 3600);
    if (!byHour.has(h)) byHour.set(h, []);
    byHour.get(h).push(Math.floor((s % 3600) / 60));
  }
  return [...byHour.entries()].sort((a, b) => a[0] - b[0]).map(([h, mins]) => [h, [...new Set(mins)].sort((a, b) => a - b)]);
};

