const shell = ({ title, lang, body }) => `<!doctype html>
<html lang="${esc(lang)}"><head><meta charset="utf-8"><title>${esc(title)}</title><meta name="viewport" content="width=device-width, initial-scale=1"><style>${CSS}</style></head><body><div class="page">${body}</div></body></html>`;

const matrixTable = (stopsInfo, trips) => {
  // Rows: the union of stops in pattern order, the longest pattern first.
  const order = [];
  const seen = new Set();
  const patterns = [...trips].sort((a, b) => b.stops.length - a.stops.length);
  for (const t of patterns) for (const s of t.stops) if (!seen.has(s.stop_id)) { seen.add(s.stop_id); order.push(s.stop_id); }
  const sorted = [...trips].sort((a, b) => a.stops[0].dep - b.stops[0].dep);
  const head = `<tr><th class="stop"></th>${sorted.map((t) => `<th>${esc(hhmm(t.stops[0].dep))}</th>`).join("")}</tr>`;
  const rows = order.map((sid) => `<tr><td class="stop">${esc(stopsInfo.get(sid)?.name || sid)}</td>${sorted.map((t) => { const s = t.stops.find((x) => x.stop_id === sid); return `<td>${s && s.dep != null ? esc(hhmm(s.dep)) : "·"}</td>`; }).join("")}</tr>`).join("");
  return `<div class="wrap"><table>${head}${rows}</table></div>`;
};

const gridTable = (l, stopsInfo, trips) => {
  const order = [];
  const seen = new Set();
  for (const t of [...trips].sort((a, b) => b.stops.length - a.stops.length)) for (const s of t.stops) if (!seen.has(s.stop_id)) { seen.add(s.stop_id); order.push(s.stop_id); }
  const hours = new Set();
  const perStop = new Map();
  for (const sid of order) {
    const deps = trips.map((t) => t.stops.find((x) => x.stop_id === sid)?.dep).filter((d) => d != null);
    const g = hourGrid(deps);
    perStop.set(sid, new Map(g));
    for (const [h] of g) hours.add(h);
  }
  const hs = [...hours].sort((a, b) => a - b);
  const head = `<tr><th class="stop">${esc(l.stop)}</th>${hs.map((h) => `<th>${String(h).padStart(2, "0")}h</th>`).join("")}</tr>`;
  const rows = order.map((sid) => `<tr><td class="stop">${esc(stopsInfo.get(sid)?.name || sid)}</td>${hs.map((h) => `<td class="mins">${(perStop.get(sid).get(h) || []).map((m) => String(m).padStart(2, "0")).join(" ")}</td>`).join("")}</tr>`).join("");
  return `<div class="wrap"><table class="grid">${head}${rows}</table></div>`;
};

const timetableHtml = (db, { routeId, date, lang = "en" }) => {
  const l = L10N[lang] || L10N.en;
  const route = db.prepare("SELECT route_id, route_short_name, route_long_name, route_color, route_text_color, agency_id FROM routes WHERE route_id = ?").get(routeId);
  if (!route) return null;
  const agency = db.prepare("SELECT agency_name FROM agency WHERE agency_id = ? OR ? = ''").get(route.agency_id || "", route.agency_id || "") || db.prepare("SELECT agency_name FROM agency LIMIT 1").get();
  const sd = resolveServiceDate(db, date);
  const trips = dayTrips(db, sd.services, { routeId });
  const stopsInfo = new Map(db.prepare("SELECT stop_id, stop_name FROM stops").all().map((s) => [s.stop_id, { name: s.stop_name }]));
  const color = /^[0-9A-Fa-f]{6}$/.test(route.route_color || "") ? route.route_color : "1E88E5";
  const text = /^[0-9A-Fa-f]{6}$/.test(route.route_text_color || "") ? route.route_text_color : textColorFor(color);
  const title = `${l.line} ${route.route_short_name || route.route_id}${route.route_long_name ? ` — ${route.route_long_name}` : ""}`;
  let body = `<div class="head"><div class="badge" style="background:#${color};color:#${text}">${esc(route.route_short_name || route.route_id)}</div><div><h1>${esc(route.route_long_name || route.route_short_name || route.route_id)}</h1><div class="sub">${esc(agency?.agency_name || "")} · ${esc(l.timetable)} · ${esc(l.validOn)} ${esc(prettyDate(sd.date, l))}${sd.shifted ? ` (${esc(l.nextService)} ${esc(prettyDate(sd.date, l))})` : ""}</div></div></div>`;
  if (!trips.length) body += `<p class="note">${esc(l.noService)}</p>`;
  for (const dirId of ["0", "1"]) {
    const dt = trips.filter((t) => t.direction_id === dirId);
    if (!dt.length) continue;
    const headsign = [...dt.reduce((m, t) => m.set(t.headsign, (m.get(t.headsign) || 0) + 1), new Map()).entries()].sort((a, b) => b[1] - a[1])[0][0] || stopsInfo.get(dt[0].stops[dt[0].stops.length - 1].stop_id)?.name || "";
    body += `<h2>${esc(l.direction)} ${esc(headsign)} <span class="note">· ${dt.length} ${esc(l.trips)}</span></h2>`;
    body += dt.length <= MATRIX_MAX_TRIPS ? matrixTable(stopsInfo, dt) : gridTable(l, stopsInfo, dt);
  }
  body += `<div class="foot"><span>${esc(l.generated)}</span><span>${new Date().toISOString().slice(0, 10)}</span></div>`;
  return shell({ title, lang, body });
};

const langOf = (req) => {
  const v = String(req.query?.lang || "en").slice(0, 2).toLowerCase();
  return L10N[v] ? v : "en";
};
const dateOf = (req) => {
  const v = String(req.query?.date || "").replace(/-/g, "");
  return /^\d{8}$/.test(v) ? v : todayYmd();
};

const getTimetable = (req, res) => {
  const ctx = requireSession(req, res);
  if (!ctx) return;
  const routeId = String(req.query?.route_id || "").trim();
  if (!routeId) return res.status(400).json({ error: "INVALID_INPUT", message: "route_id is required." });
  try {
    const html = timetableHtml(ctx.db, { routeId, date: dateOf(req), lang: langOf(req) });
    if (!html) return res.status(404).json({ error: "NOT_FOUND", message: "Route not found." });
    res.setHeader("Content-Type", "text/html; charset=utf-8");
    res.send(html);
  } catch (err) {
    console.error("timetable document:", err);
    res.status(500).json({ error: "DOCUMENT_FAILED", message: err.message });
  }
};

