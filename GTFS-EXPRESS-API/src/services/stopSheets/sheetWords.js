const LANGS = Object.freeze(Object.keys(WORDS));

const wordsOf = (lang) => WORDS[lang] || WORDS.en;

const fill = (template, values) => String(template).replace(/\{(\w+)\}/g, (_, k) => (values[k] === undefined ? `{${k}}` : String(values[k])));

// English sheets are dated the European way (« 1 September 2026 »).
const localeOf = (lang) => (lang === "en" ? "en-GB" : lang);
const ymdDate = (ymd) => new Date(Date.UTC(+ymd.slice(0, 4), +ymd.slice(4, 6) - 1, +ymd.slice(6, 8)));

// French writes the first of the month « 1er ».
const firstOfMonth = (text, ymd, lang) => (lang === "fr" && ymd.slice(6, 8) === "01" ? text.replace(/^1(?=\D)/, "1er") : text);

/** A date of the sheet: "11 novembre" (with the year when asked). */
const dateText = (ymd, lang, { year = false, weekday = false } = {}) => {
  try {
    const text = new Intl.DateTimeFormat(localeOf(lang), { day: "numeric", month: "long", ...(year ? { year: "numeric" } : {}), ...(weekday ? { weekday: "long" } : {}), timeZone: "UTC" }).format(ymdDate(ymd));
    return weekday && lang === "fr" ? text.replace(/(^|\s)1(?=\s)/, (_, sp) => sp + "1er") : firstOfMonth(text, ymd, lang);
  } catch {
    return `${ymd.slice(6, 8)}/${ymd.slice(4, 6)}${year ? `/${ymd.slice(0, 4)}` : ""}`;
  }
};

/** The day alone ("6", "6.", "6日"), for the first date of a range within one month. */
const dayText = (ymd, lang) => {
  try {
    return firstOfMonth(new Intl.DateTimeFormat(localeOf(lang), { day: "numeric", timeZone: "UTC" }).format(ymdDate(ymd)), ymd, lang);
  } catch {
    return String(+ymd.slice(6, 8));
  }
};

module.exports = { WORDS, LANGS, wordsOf, fill, dateText, dayText };
